const createFloor = (floor: number, reservedIds: string[]): ParkingFloor => ({
  floor,
  title: floor === 1 ? 'Ground Level' : floor === 2 ? 'Mid Level' : 'Top Level',
  spaces: ['A', 'B', 'C', 'D'].flatMap(row =>
    Array.from({ length: 8 }, (_, index) => {
      const id = `${row}-${index + 1}`;
      return {
        id,
        row,
        number: index + 1,
        status: reservedIds.includes(id) ? 'reserved' : 'available',
      } as const;
    }),
  ),
});

